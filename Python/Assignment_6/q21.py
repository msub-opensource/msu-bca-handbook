# Question 21: Demonstrate the use of various functions on a tuple (min, max, len)

num_tuple = (45, 12, 89, 34, 67, 23)

print("Tuple:", num_tuple)
print("Length using len():", len(num_tuple))
print("Minimum element using min():", min(num_tuple))
print("Maximum element using max():", max(num_tuple))
print("Sum of elements using sum():", sum(num_tuple))
