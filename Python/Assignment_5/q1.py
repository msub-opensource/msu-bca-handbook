# Create strings using:
# 1. Single quotes
# 2. Double quotes
# 3. Triple single quotes
# 4. Triple double quotes
# 5. Display each string and its type using type().

# 1. Single quotes
s1 = 'Hello with Single Quotes'

# 2. Double quotes
s2 = "Hello with Double Quotes"

# 3. Triple single quotes
s3 = '''Hello with
Triple Single Quotes'''

# 4. Triple double quotes
s4 = """Hello with
Triple Double Quotes"""

# 5. Display each string and its type
print(f"s1: {s1} | Type: {type(s1)}")
print(f"s2: {s2} | Type: {type(s2)}")
print(f"s3: {s3} | Type: {type(s3)}")
print(f"s4: {s4} | Type: {type(s4)}")
