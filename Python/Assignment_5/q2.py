# Question 2: String Indexing
# Given: text = "PYTHON PROGRAMMING"
# Display:
# 1. First character
# 2. Last character
# 3. Fifth character
# 4. Character at index -3
# 5. Character at index 4

text = "PYTHON PROGRAMMING"

# 1. First character (index 0)
print("1. First character:", text[0])

# 2. Last character (index -1)
print("2. Last character:", text[-1])

# 3. Fifth character (1st is 0, 5th is index 4)
print("3. Fifth character:", text[4])

# 4. Character at index -3
print("4. Character at index -3:", text[-3])

# 5. Character at index 4
print("5. Character at index 4:", text[4])
